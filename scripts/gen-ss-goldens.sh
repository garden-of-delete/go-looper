#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
SIST_DIR="$(cd "${SIST_DIR:-$REPO_ROOT/../SIST}" && pwd)"
PATCH_FILE="$SCRIPT_DIR/sist-1r.patch"
FIXTURES="$REPO_ROOT/testdata/fixtures"
GOLDEN_DIR="$REPO_ROOT/testdata/golden/ss"
EXPECTED_COMMIT="cc206d0d22b0c631e8ee801e8cbd94aa61adbf90"

SIST_COMMIT="$(git -C "$SIST_DIR" rev-parse HEAD)"
if [ "$SIST_COMMIT" != "$EXPECTED_COMMIT" ]; then
    echo "SIST is at $SIST_COMMIT, expected $EXPECTED_COMMIT" >&2
    exit 1
fi

REFERENCE="$SIST_DIR/tests/regression/reference/v1.0.0/melting.txt"
TOY_FA="$FIXTURES/pbr322.toy.fa"
SYNTH_FA="$FIXTURES/ss_synth1600.fa"
for f in "$PATCH_FILE" "$REFERENCE" "$TOY_FA" "$SYNTH_FA"; do
    if [ ! -f "$f" ]; then
        echo "missing file: $f" >&2
        exit 1
    fi
done
if ! cmp -s "$TOY_FA" "$SIST_DIR/tests/regression/data/pbr322.toy.fa"; then
    echo "$TOY_FA differs from the SIST copy" >&2
    exit 1
fi

BUILD_DIR="$(mktemp -d)"
trap 'rm -rf "$BUILD_DIR"' EXIT

SRC_DIR="$BUILD_DIR/trans_three"
cp -R "$SIST_DIR/src/trans_three" "$SRC_DIR"

echo "--- building unpatched qsidd ---"
make -C "$SRC_DIR"

echo "--- build sanity: unpatched melting run vs reference ---"
SANITY_DIR="$BUILD_DIR/sanity"
mkdir "$SANITY_DIR"
cp "$TOY_FA" "$SANITY_DIR/pbr322.toy.fa"
(cd "$SANITY_DIR" && "$SRC_DIR/qsidd" -b -p -r -f pbr322.toy.fa > stdout.txt)
if ! diff <(grep -v '^Run time' "$SANITY_DIR/stdout.txt") <(grep -v '^Run time' "$REFERENCE") > /dev/null; then
    echo "unpatched build does not reproduce $REFERENCE" >&2
    exit 1
fi

echo "--- applying sist-1r.patch (patch -p1, run inside the scratch copy of src/trans_three) ---"
(cd "$SRC_DIR" && patch -p1 < "$PATCH_FILE")
make -C "$SRC_DIR" clean
make -C "$SRC_DIR"

run_case() {
    local case_name="$1"
    local fasta="$2"
    shift 2
    local run_dir="$BUILD_DIR/run/$case_name"
    local fasta_name
    fasta_name="$(basename "$fasta")"
    mkdir -p "$run_dir"
    cp "$fasta" "$run_dir/$fasta_name"
    echo "--- running case: $case_name ---"
    (cd "$run_dir" && "$SRC_DIR/qsidd" -b -p -r "$@" -f "$fasta_name" > stdout.raw)
    mkdir -p "$GOLDEN_DIR/$case_name"
    grep -v '^Run time' "$run_dir/stdout.raw" > "$GOLDEN_DIR/$case_name/stdout.txt"
}

verify_case() {
    local case_name="$1"
    local expected_rows="$2"
    local golden="$GOLDEN_DIR/$case_name/stdout.txt"
    local rows
    if [ ! -s "$golden" ]; then
        echo "missing or empty: $golden" >&2
        exit 1
    fi
    if grep -Eq '^Number of (two|three|four)-run states' "$golden"; then
        echo "$golden contains multi-run output; 1R patch did not take effect" >&2
        exit 1
    fi
    rows="$(grep -Ec $'^[0-9]+\t[ACGT]\t' "$golden")"
    if [ "$rows" != "$expected_rows" ]; then
        echo "$golden has $rows table rows, expected $expected_rows" >&2
        exit 1
    fi
}

mkdir -p "$GOLDEN_DIR"
run_case clamp-copoly-defaults "$TOY_FA"
run_case clamp-nn-defaults "$TOY_FA" -n
run_case circular-copoly-defaults "$TOY_FA" -c
run_case circular-nn-defaults "$TOY_FA" -c -n
run_case clamp-copoly-alt "$TOY_FA" -T 315 -i 0.1 -s 0.04 -t 10
run_case clamp-copoly-synth "$SYNTH_FA"
run_case circular-nn-synth "$SYNTH_FA" -c -n

echo "--- verifying goldens ---"
verify_case clamp-copoly-defaults 4361
verify_case clamp-nn-defaults 4361
verify_case circular-copoly-defaults 4361
verify_case circular-nn-defaults 4361
verify_case clamp-copoly-alt 4361
verify_case clamp-copoly-synth 1600
verify_case circular-nn-synth 1600

echo "--- writing README ---"
PATCH_SHA="$(shasum -a 256 "$PATCH_FILE" | cut -d' ' -f1)"
COMPILER="$(c++ --version | head -1)"
cat > "$GOLDEN_DIR/README.md" <<README
# SIST 1R golden reference data

Generated by \`scripts/gen-ss-goldens.sh\`.

- SIST commit: \`$SIST_COMMIT\`
- Compiler: \`$COMPILER\`
- \`scripts/sist-1r.patch\` sha256: \`$PATCH_SHA\`

## Build

\`src/trans_three\` is copied to a scratch directory and built with plain \`make\`
(\`c++ -O2 -Wall\`). Before patching, the unpatched binary is run as
\`./qsidd -b -p -r -f pbr322.toy.fa\` and its output must match
\`tests/regression/reference/v1.0.0/melting.txt\` (ignoring \`^Run time\` lines).

\`scripts/sist-1r.patch\` is a \`diff -u\` against the pristine \`qsidd.cpp\` with
paths \`a/qsidd.cpp\` and \`b/qsidd.cpp\`. It is applied with \`patch -p1\` run inside the
scratch copy of \`src/trans_three\`. It comments out the \`Search_Low2RE\`,
\`Search_Low3RE\` and \`Search_Low4RE\` calls in \`main\`, restricting SIST to at most
one open run (1R), so no golden contains a \`Number of two-run states\`, \`three-run\` or \`four-run\` line
(the unpatched reference prints them; the patched binary does not).

## Cases

Each case runs in its own directory containing a copy of the fixture, with
stdout captured and \`^Run time\` lines removed (wall-clock dependent).
\`-f <file>\` must be the last arguments.

| case | command |
|---|---|
| \`clamp-copoly-defaults\` | \`qsidd -b -p -r -f pbr322.toy.fa\` |
| \`clamp-nn-defaults\` | \`qsidd -b -p -r -n -f pbr322.toy.fa\` |
| \`circular-copoly-defaults\` | \`qsidd -b -p -r -c -f pbr322.toy.fa\` |
| \`circular-nn-defaults\` | \`qsidd -b -p -r -c -n -f pbr322.toy.fa\` |
| \`clamp-copoly-alt\` | \`qsidd -b -p -r -T 315 -i 0.1 -s 0.04 -t 10 -f pbr322.toy.fa\` |
| \`clamp-copoly-synth\` | \`qsidd -b -p -r -f ss_synth1600.fa\` |
| \`circular-nn-synth\` | \`qsidd -b -p -r -c -n -f ss_synth1600.fa\` |

## Fixtures

- \`testdata/fixtures/pbr322.toy.fa\`: verbatim copy of \`SIST/tests/regression/data/pbr322.toy.fa\`.
- \`testdata/fixtures/ss_synth1600.fa\` (generated once, never regenerated):

\`\`\`
python3 -c "import random; random.seed(1600); s=''.join(random.choice('ACGT') for _ in range(1600)); print('>SS_SYNTH1600'); [print(s[i:i+70]) for i in range(0,1600,70)]" > testdata/fixtures/ss_synth1600.fa
\`\`\`
README

echo "done. goldens written to $GOLDEN_DIR"
